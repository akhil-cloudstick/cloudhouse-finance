// lastDueDate returns the latest DueDate across installments — used both to
// find the current schedule's end (evaluateAndApplyPenal) and, via
// isPastGracePeriod, to decide whether a Pending loan can revert to Active
// (RecordPayment).
func lastDueDate(installments []PersonalLoanInstallment) time.Time {
	var last time.Time
	for _, inst := range installments {
		if inst.DueDate.After(last) {
			last = inst.DueDate
		}
	}
	return last
}

// isPastGracePeriod reports whether asOf is past loan's CURRENT schedule's
// last installment due date plus GracePeriodDays — the same "went unpaid
// past its schedule and grace period" condition evaluateAndApplyPenal fires
// on, factored out so RecordPayment can use it too (to decide whether a
// Pending loan is current again after a payment) without duplicating the
// due-date-scan logic.
func isPastGracePeriod(loan *PersonalLoan, installments []PersonalLoanInstallment, asOf time.Time) bool {
	if len(installments) == 0 {
		return false
	}
	graceEnd := lastDueDate(installments).AddDate(0, 0, loan.GracePeriodDays)
	return asOf.After(graceEnd)
}

// evaluateAndApplyPenal checks whether loan's penal interest should fire as
// of asOf, and if so computes the new outstanding balance and a fresh
// installment schedule for it. It does not mutate loan or hit the database —
// applyPenalIfDue applies the result inside a transaction, the same
// separation projectAccrual/accrueAndSave use for gold loans.
//
// Penal interest fires once the grace period after the schedule's LAST
// installment due date has elapsed with OutstandingAmount still owed, and
// applies to the whole OutstandingAmount (never a single installment's
// amount) at the loan's FULL PenalInterestRate — a flat percentage charged
// once per cycle, e.g. 10% on ₹8000 owed is ₹800, with no division by
// days/weeks/months in a year. Firing folds the charge directly into
// OutstandingAmount and regenerates a whole new TenureCount-length schedule
// anchored at asOf, so a still-unpaid loan effectively restarts its
// repayment cycle rather than accruing a running penal total the way gold
// loans do. Also fires on an already-Pending loan (a loan can go through
// more than one penal cycle).
func evaluateAndApplyPenal(loan *PersonalLoan, installments []PersonalLoanInstallment, asOf time.Time) (fires bool, penalAmount float64, newInstallments []PersonalLoanInstallment) {
	switch loan.Status {
	case StatusActive, StatusPending:
	default:
		return false, 0, nil
	}
	if (loan.PenalInterestRate <= 0 && loan.PenalFlatAmount <= 0) || loan.OutstandingAmount <= epsilon {
		return false, 0, nil
	}
	if !isPastGracePeriod(loan, installments, asOf) {
		return false, 0, nil
	}
	lastDue := lastDueDate(installments)

	// The current schedule was itself generated by the last penal charge (or
	// by CreateLoan, for cycle 0) at LastPenalAppliedAt — if that's still
	// after graceEnd was last evaluated, or more simply if it's on/after
	// lastDue, this exact cycle has already been charged and must not fire
	// again on the next tick within the same overdue window.
	if loan.LastPenalAppliedAt != nil && !loan.LastPenalAppliedAt.Before(lastDue) {
		return false, 0, nil
	}

	// PenalInterestRate always wins when set (whether it's a Percentage
	// loan's own default or an explicit override on ANY loan, Flat included)
	// — PenalFlatAmount only applies as the Flat-loan fallback when no rate
	// was ever set. See PersonalLoan.PenalInterestRate/PenalFlatAmount's doc
	// comment.
	if loan.PenalInterestRate > 0 {
		penalAmount = platform.RoundMoney(loan.OutstandingAmount * loan.PenalInterestRate / 100)
	} else {
		penalAmount = platform.RoundMoney(loan.PenalFlatAmount)
	}
	if penalAmount <= 0 {
		return false, 0, nil
	}
	newOutstanding := platform.RoundMoney(loan.OutstandingAmount + penalAmount)

	scheduleLoan := *loan
	scheduleLoan.PrincipalAmount = newOutstanding
	scheduleLoan.InstallmentAmount = platform.RoundMoney(newOutstanding / float64(loan.TenureCount))
	newInstallments = generateScheduleFrom(&scheduleLoan, asOf)
	for i := range newInstallments {
		newInstallments[i].PersonalLoanID = loan.ID
	}
	return true, penalAmount, newInstallments
}

// SweepPenalInterest is the background-job entry point (mirrors gold loan's
// CheckDueAndOverdueLoans): it evaluates every Active loan with a
// PenalInterestRate configured and applies a penal charge + schedule
// regeneration to each one whose grace period has elapsed, per-loan, inside
// its own transaction with a row lock so it can't race a concurrent payment.
// Deliberately sends no notification — unlike gold loans' due/overdue SMS,
// personal-loan penal charges are silent.
func (s *Service) SweepPenalInterest(ctx context.Context) error {
	loans, err := s.repo.FindActiveForPenalSweep(ctx)
	if err != nil {
		return err
	}
	now := time.Now()
	for _, l := range loans {
		if err := s.applyPenalIfDue(ctx, l.ID, now); err != nil {
			log.Printf("penal interest sweep failed for personal loan %d: %v", l.ID, err)
		}
	}
	return nil
}

// applyPenalIfDue re-locks a single loan and its current schedule, re-checks
// evaluateAndApplyPenal against the freshly locked row (guards against a
// payment or a previous tick changing OutstandingAmount/LastPenalAppliedAt
// between FindActiveForPenalSweep's read and this transaction), and persists
// the charge + new schedule if it still fires.
func (s *Service) applyPenalIfDue(ctx context.Context, loanID uint, asOf time.Time) error {
	return s.repo.DB().WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		loan, err := s.repo.LockByID(ctx, tx, loanID, nil)
		if err != nil {
			if errors.Is(err, gorm.ErrRecordNotFound) {
				return nil
			}
			return err
		}
		var installments []PersonalLoanInstallment
		if err := tx.Where("personal_loan_id = ?", loanID).Find(&installments).Error; err != nil {
			return err
		}

		fires, penalAmount, newInstallments := evaluateAndApplyPenal(loan, installments, asOf)
		if !fires {
			return nil
		}

		loan.OutstandingAmount = platform.RoundMoney(loan.OutstandingAmount + penalAmount)
		loan.TotalPenalInterestCharged = platform.RoundMoney(loan.TotalPenalInterestCharged + penalAmount)
		loan.PenalCycleCount++
		loan.LastPenalAppliedAt = &asOf
		// A charge just fired specifically because the loan is past its
		// (former) schedule's grace period with a balance still owed — mark
		// it Pending. See PersonalLoan.StatusPending's doc comment; this is
		// the ONLY place Status is ever set TO Pending — RecordPayment is
		// the only place it's set back to Active.
		loan.Status = StatusPending
		if err := s.repo.Update(ctx, tx, loan); err != nil {
			return err
		}
		for i := range newInstallments {
			newInstallments[i].TenantID = loan.TenantID
		}
		if err := s.repo.ReplaceInstallments(ctx, tx, loan.ID, newInstallments); err != nil {
			return err
		}
		return s.logHistory(ctx, tx, loan.ID, loan.TenantID, EventPenalApplied,
			fmt.Sprintf("Installment period ended unpaid — ₹%.2f penal interest added (cycle %d)", penalAmount, loan.PenalCycleCount), penalAmount, nil, asOf)
	})
}
